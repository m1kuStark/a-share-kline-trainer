import { expect, test } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  const active = await (await page.request.get('/api/trainings/active')).json()
  if (active.training) await page.request.post(`/api/trainings/${active.training.id}/abandon`)
  await page.goto('/')
  await expect(page.locator('.launcher')).toBeVisible()
})

test('UIUX navigation identifies the current page and settles without moving repeated targets', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  const history = page.getByRole('button', { name: '历史训练', exact: true })
  const railBefore = await history.boundingBox()
  await history.click()
  await expect(history).toHaveAttribute('aria-current', 'page')
  const content = page.locator('.history-page')
  await expect(content).toBeVisible()
  expect(await content.evaluate(el => getComputedStyle(el).animationName)).toBe('workbench-enter')
  await content.evaluate(async el => { await Promise.all(el.getAnimations().map(a => a.finished)) })
  expect(await content.evaluate(el => getComputedStyle(el).opacity)).toBe('1')
  expect(await history.boundingBox()).toEqual(railBefore)
  await page.getByRole('button', { name: '历史排行', exact: true }).click()
  await history.click()
  await expect(content).toBeVisible()
  await expect(page.locator('.rail [aria-current="page"]')).toHaveCount(1)
  await page.getByRole('button', { name: '训练录像', exact: true }).click()
  const library = page.getByRole('region', { name: '训练录像库', exact: true })
  await expect(library).toBeVisible()
  expect(await library.evaluate(el => getComputedStyle(el).animationName)).toBe('workbench-enter')
  await page.getByRole('button', { name: '训练', exact: true }).click()
  await expect(page.locator('.launcher')).toBeVisible()
})

test('UIUX reduced motion preserves navigation and settings keyboard recovery', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  const history = page.getByRole('button', { name: '历史训练', exact: true })
  await history.click()
  await expect(history).toHaveAttribute('aria-current', 'page')
  expect(await page.locator('.history-page').evaluate(el => getComputedStyle(el).animationName)).toBe('none')
  const settings = page.getByRole('button', { name: '训练默认设置', exact: true })
  await settings.click()
  await expect(page.getByRole('dialog', { name: '训练默认设置', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog', { name: '训练默认设置', exact: true })).toHaveCount(0)
  await expect(settings).toBeFocused()
  await expect(history).toHaveAttribute('aria-current', 'page')
})

test('UIUX fixed navigation targets accept reverse actions while entry motion is running', async ({ page }) => {
  await page.setViewportSize({ width: 1008, height: 641 })
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  const history = page.getByRole('button', { name: '历史训练', exact: true })
  const rankings = page.getByRole('button', { name: '历史排行', exact: true })
  const settings = page.getByRole('button', { name: '训练默认设置', exact: true })
  const positions = await Promise.all([history, rankings, settings].map(el => el.boundingBox()))
  expect(positions.every(Boolean)).toBe(true)
  const point = (index: number) => ({ x: positions[index]!.x + positions[index]!.width / 2, y: positions[index]!.y + positions[index]!.height / 2 })
  const click = async (index: number) => { const p = point(index); await page.mouse.click(p.x, p.y) }
  await click(0)
  // Observe a live transition before interrupting it; settled-only clicks do not cover this path.
  const motion = await page.locator('.history-page').evaluate(el => el.getAnimations().map(a => ({ state: a.playState, progress: a.effect?.getComputedTiming().progress })))
  expect(motion.some(a => a.state === 'running' && a.progress !== null && a.progress! < 1)).toBe(true)
  await click(1)
  await expect(rankings).toHaveAttribute('aria-current', 'page')
  await expect(page.locator('.rankings-page')).toBeVisible()
  expect(await rankings.boundingBox()).toEqual(positions[1])
  await click(0)
  await expect(history).toHaveAttribute('aria-current', 'page')
  await expect(page.locator('.history-page')).toBeVisible()
  await expect(page.locator('.rankings-page')).toHaveCount(0)
  expect(await history.boundingBox()).toEqual(positions[0])
  await click(2)
  const dialog = page.getByRole('dialog', { name: '训练默认设置', exact: true })
  expect(await dialog.evaluate(el => el.getAnimations().some(a => a.playState === 'running'))).toBe(true)
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(settings).toBeFocused()
  expect(await page.locator('.workspace').evaluate(el => el.inert)).toBe(false)
  await click(2)
  await expect(dialog).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
})
